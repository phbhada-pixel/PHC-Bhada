function standardizeSourceType(rawType) {
  const t = (rawType || '').trim();
  if (t === 'नळयोजना' || t.includes('नळ')) return 'सार्वजनिक पाणीपुरवठा योजना (नळ योजना)';
  if (t === 'हातपेप' || t === 'हातपंप') return 'हातपंप';
  if (t === 'विदयूतपंप' || t === 'विद्युतपंप' || t.includes('विद्युत') || t.includes('विदयूत')) return 'विद्युत पंप';
  if (t === 'विहीर') return 'विहीर';
  if (t === 'आड') return 'आड';
  if (t === 'Aqua Plant' || t === 'RO Plant' || t.includes('Aqua') || t.includes('RO')) return 'RO Plant';
  if (t.includes('स्टॅन्ड')) return 'स्टॅन्ड पोस्ट';
  return 'इतर';
}

function determineOwnership(desc, village) {
  const d = (desc || '').trim();
  // Known private individual names / commercial plants
  const privateKeywords = [
    'स्वराज ॲक्वा', 'मातोश्री एक्वा', 'My Aqua Fresh', 'माधवी शिवाप्पा वाले',
    'बाळकृष्ण सुरेश बंडे', 'चांगदेव गवळी', 'शिवाजी शंकरराव पाटील', 'समद पठाण',
    'हारुन युसूफ', 'बापुराव शिखरे', 'लिंबाजी शिखरे', 'राजाराम जंगाले', 'कीशोर मिसाळ',
    'क्रीशोर मिसाळ', 'देशपांडे', 'आशोक राठोड', 'चव्हाण', 'रावण शिंदे', 'दत्तु उबाळे',
    'चंद्रप्पा हुरदूळे', 'च्रद्राप्पा', 'बाबा भांगे', 'शेळके', 'मनोज पाटील'
  ];

  for (const kw of privateKeywords) {
    if (d.includes(kw)) return 'खाजगी';
  }

  // Grampanchayat / ZP / Government / Public places
  if (d.includes('ग्रामपंचायत') || d.includes('सार्वजनीक') || d.includes('सार्वजनिक') || 
      d.includes('जि.प.') || d.includes('जिल्हा परिषद') || d.includes('शाळा') || 
      d.includes('मंदिर') || d.includes('मंदीर') || d.includes('गायरान') || 
      d.includes('उपकेंद्र') || d.includes('आरोग्य केंद्र') || d.includes('पोलीस') || d.includes('बस स्टॅन्ड')) {
    return 'शासकीय';
  }

  return 'शासकीय'; // Default for village community water sources
}

function processData() {
  const lines = rawCsvData.trim().split('\n');
  const cleanedSources = [];

  // Filter out headers
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const parts = line.split(',');
    if (parts.length < 6) continue;

    const subcenter = parts[0].trim();
    const gramPanchayat = parts[1].trim();
    const village = parts[2].trim();
    const rawSourceId = parts[3].trim();
    const rawType = parts[4].trim();
    const locationDesc = parts[5].trim();

    // Check for temporary / dummy tags
    if (rawSourceId.includes('TEST') || locationDesc.toLowerCase().includes('dummy') || locationDesc.toLowerCase().includes('temp')) {
      console.log(`Removing dummy source: ${rawSourceId} - ${locationDesc}`);
      continue;
    }

    const sourceType = standardizeSourceType(rawType);
    const ownership = determineOwnership(locationDesc, village);
    
    let sourceCode = rawSourceId.startsWith('SRC-') ? rawSourceId : `SRC-${rawSourceId}`;
    
    // Construct readable Source Name
    let sourceName = `${village} ${locationDesc}`;
    if (!sourceName.includes(sourceType) && !sourceName.includes('नळयोजना')) {
      sourceName += ` (${sourceType})`;
    }

    cleanedSources.push({
      id: `SRC_REGISTERED_${rawSourceId}`,
      sourceCode: sourceCode,
      sourceId: sourceCode,
      subcenter: subcenter,
      gramPanchayat: gramPanchayat,
      village: village,
      sourceName: sourceName,
      sourceType: sourceType,
      ownership: ownership,
      status: "Active",
      location: locationDesc,
      createdDate: "2026-01-01"
    });
  }

  console.log(`Processed ${cleanedSources.length} clean permanent water sources.`);

  // Write to nwbdcp_db.json
  const dbPath = path.join(__dirname, '../data/nwbdcp_db.json');
  let currentDb = { waterSources: [], sampleDispatches: [], sampleResults: [], retests: [], auditLogs: [] };
  
  if (fs.existsSync(dbPath)) {
    try {
      currentDb = JSON.parse(fs.readFileSync(dbPath, 'utf8'));
    } catch (e) {}
  }

  currentDb.waterSources = cleanedSources;
  currentDb.lastSaved = new Date().toISOString();

  fs.writeFileSync(dbPath, JSON.stringify(currentDb, null, 2), 'utf8');
  console.log(`Updated data/nwbdcp_db.json with ${cleanedSources.length} sources.`);

  return cleanedSources;
}

